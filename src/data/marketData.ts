// Generates time series data for the detailed chart modal
export function generateChartData(basePrice: number, timeframe: string, isPositive: boolean) {
  const pointsCount = timeframe === '1D' ? 24 : timeframe === '5D' ? 30 : timeframe === '1M' ? 30 : timeframe === '1Y' ? 48 : 60;
  const result = [];
  const startMultiplier = isPositive ? 0.96 : 1.04;
  let current = basePrice * startMultiplier;

  for (let i = 0; i < pointsCount; i++) {
    const progress = i / (pointsCount - 1);
    const trendTarget = basePrice;
    const noise = (Math.random() - 0.48) * (basePrice * 0.015);
    current = current + (trendTarget - current) * (progress * 0.5) + noise;

    let timeLabel = '';
    if (timeframe === '1D') {
      const hour = 9 + Math.floor((i / pointsCount) * 7);
      const min = Math.floor(((i % 4) * 15));
      timeLabel = `${hour.toString().padStart(2, '0')}:${min.toString().padStart(2, '0')}`;
    } else if (timeframe === '5D') {
      const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri'];
      const dayIndex = Math.min(Math.floor((i / pointsCount) * 5), 4);
      timeLabel = `${days[dayIndex]} ${10 + (i % 6)}h`;
    } else if (timeframe === '1M') {
      timeLabel = `Day ${i + 1}`;
    } else {
      const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
      timeLabel = `${months[i % 12]} ${2024 + Math.floor(i / 12)}`;
    }

    result.push({
      time: timeLabel,
      price: Number(current.toFixed(2)),
      volume: Math.floor(Math.random() * 500000 + 100000)
    });
  }

  // Ensure last point hits exact basePrice
  result[result.length - 1].price = basePrice;
  return result;
}
